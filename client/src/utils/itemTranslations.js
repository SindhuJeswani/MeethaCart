/**
 * Returns the translated item title based on current language
 */
export const getItemTitle = (itemOrTitle, lang) => {
  if (!itemOrTitle) return '';
  const isUr = lang === 'ur';

  // If already in English and not Urdu, return standard title
  if (!isUr) {
    if (typeof itemOrTitle === 'object') {
      return itemOrTitle.title || '';
    }
    return String(itemOrTitle);
  }

  // 1. Direct property if provided on model
  if (typeof itemOrTitle === 'object' && itemOrTitle.titleUr) {
    return itemOrTitle.titleUr;
  }

  const rawTitle = typeof itemOrTitle === 'object' ? itemOrTitle.title : String(itemOrTitle);
  if (!rawTitle) return '';

  // 2. Exact dictionary lookup
  const match = ITEM_TRANSLATIONS[rawTitle];
  if (match?.titleUr) return match.titleUr;

  // 3. Normalized case-insensitive lookup
  const lower = rawTitle.toLowerCase().trim();
  for (const [key, val] of Object.entries(ITEM_TRANSLATIONS)) {
    if (key.toLowerCase().trim() === lower) {
      return val.titleUr;
    }
  }

  // 4. Keyword-based intelligent fallback for common Pakistani bakery terms
  if (lower.includes('gulab jamun')) return 'دیسی گھی گلاب جامن';
  if (lower.includes('barfi') || lower.includes('burfi')) return 'شاہی کھویا برفی';
  if (lower.includes('jalebi')) return 'خستہ زعفرانی جلیبی';
  if (lower.includes('ladoo') || lower.includes('laddu')) return 'موتی چور لڈو';
  if (lower.includes('nan khatai') || lower.includes('nankhatai')) return 'لاہوری بادامی نان خطائی';
  if (lower.includes('fudge cake') || (lower.includes('chocolate') && lower.includes('cake'))) return 'چاکلیٹ فج کیک';
  if (lower.includes('red velvet')) return 'ریڈ ویلوٹ کیک';
  if (lower.includes('biscoff')) return 'لوٹس بسکوف کیک';
  if (lower.includes('mango') && lower.includes('cake')) return 'تازہ آم کا کیک';
  if (lower.includes('sourdough')) return 'کنٹری سورڈو بریڈ';
  if (lower.includes('brioche')) return 'فرینچ بٹر بریوش';
  if (lower.includes('focaccia')) return 'روزمیری فوکاشیا بریڈ';
  if (lower.includes('chocolate chip') || lower.includes('cookie')) return 'چاکلیٹ چپ کوکیز';
  if (lower.includes('brownie')) return 'سالٹڈ کیریمل براؤنی';
  if (lower.includes('cupcake')) return 'کلاسک کپ کیکس';
  if (lower.includes('croissant')) return 'بادامی بٹر کروسان';
  if (lower.includes('tart')) return 'لیمن بٹر ٹارٹس';

  return rawTitle;
};

/**
 * Returns the translated item description based on current language
 */
export const getItemDescription = (itemOrDesc, lang) => {
  if (!itemOrDesc) return '';
  const isUr = lang === 'ur';

  if (!isUr) {
    if (typeof itemOrDesc === 'object') {
      return itemOrDesc.description || '';
    }
    return String(itemOrDesc);
  }

  if (typeof itemOrDesc === 'object' && itemOrDesc.descriptionUr) {
    return itemOrDesc.descriptionUr;
  }

  const rawDesc = typeof itemOrDesc === 'object' ? itemOrDesc.description : String(itemOrDesc);
  const rawTitle = typeof itemOrDesc === 'object' ? itemOrDesc.title : '';

  if (rawTitle && ITEM_TRANSLATIONS[rawTitle]?.descUr) {
    return ITEM_TRANSLATIONS[rawTitle].descUr;
  }

  for (const [key, val] of Object.entries(ITEM_TRANSLATIONS)) {
    if (val.descUr && rawDesc && rawDesc.includes(key.substring(0, 15))) {
      return val.descUr;
    }
  }

  return rawDesc;
};
